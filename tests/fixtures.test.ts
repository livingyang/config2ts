import { execFileSync } from "child_process";
import * as fs from "fs";
import * as path from "path";
import { test } from "node:test";
import assert from "node:assert/strict";
// Compiled together with src by tsconfig.test.json, so this resolves to
// .test-build/src/config2ts.js at runtime (same compiler options as the lib build).
import { GetTsStringFromFileList, GetValidFileList } from "../src/config2ts";

// Compiled to .test-build/tests/, so the repository root is two levels up.
const rootDir = path.resolve(__dirname, "../..");
const fixturesDir = path.join(rootDir, "fixtures");
const HEADER = "// Auto Generated by config2ts, DO NOT EDIT\n\n";

// Each fixture case is a directory of source tables (csv/ini/toml) plus a
// committed golden file `expected.ts` generated from those tables. The same
// pairs later feed the demo site (input → output comparison), so the golden
// test is what guarantees the demo can never drift from actual tool behavior.
// Regenerate with `npm run fixtures:regen` and review the diff manually.
function fixtureCases(): string[] {
  return fs
    .readdirSync(fixturesDir, { withFileTypes: true })
    .filter((e) => e.isDirectory())
    .map((e) => e.name)
    .sort();
}

function generateForCase(caseName: string): string {
  const caseDir = path.join(fixturesDir, caseName);
  const sources = GetValidFileList(fs.readdirSync(caseDir))
    .sort()
    .map((f) => path.join(caseDir, f));
  return HEADER + GetTsStringFromFileList(sources);
}

for (const caseName of fixtureCases()) {
  test(`fixture ${caseName} matches golden file`, function () {
    const expected = fs.readFileSync(path.join(fixturesDir, caseName, "expected.ts"), "utf-8");
    assert.equal(generateForCase(caseName), expected);
  });
}

// The committed golden files are demo artifacts too, so they must be valid
// TypeScript on their own — one tsc invocation over every case at once.
test("all fixture golden files compile", { timeout: 120000 }, function () {
  const goldenFiles = fixtureCases()
    .map((c) => path.join(fixturesDir, c, "expected.ts"))
    .filter((p) => fs.existsSync(p));
  // Composite goldens (merged across cases) are demo artifacts too.
  const compositeDir = path.join(rootDir, "tests", "golden");
  if (fs.existsSync(compositeDir)) {
    for (const f of fs.readdirSync(compositeDir)) {
      if (f.endsWith(".expected.ts")) goldenFiles.push(path.join(compositeDir, f));
    }
  }
  assert.ok(goldenFiles.length > 0, "no fixture golden files found");

  const tscPath = path.join(rootDir, "node_modules/typescript/bin/tsc");
  let failed = false;
  let output = "";
  try {
    execFileSync(
      process.execPath,
      [tscPath, "--noEmit", "--skipLibCheck", "--target", "ES2021", "--module", "ES2022", ...goldenFiles],
      { encoding: "utf-8" },
    );
  } catch (e: unknown) {
    failed = true;
    const err = e as { stdout?: string; stderr?: string; message?: string };
    output = `${err.stdout ?? ""}${err.stderr ?? ""}${err.message ?? ""}`;
  }
  assert.equal(failed, false, `golden files failed to compile:\n${output}`);
});
