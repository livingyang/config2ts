import * as fs from "fs";
import * as path from "path";
import { test } from "node:test";
import assert from "node:assert/strict";
import { GetTsStringFromFileList, GetValidFileList } from "../src/config2ts";

// The demo site dogfoods the tool: its own trilingual UI strings table is
// compiled by config2ts into website/src/i18n/ui.ts. Keep the committed output
// in sync — regenerate with `npm run fixtures:regen`.
const rootDir = path.resolve(__dirname, "../..");
const i18nDir = path.join(rootDir, "website/src/i18n");

test("site i18n table output is up to date", function () {
  const sources = GetValidFileList(fs.readdirSync(i18nDir))
    .sort()
    .map((f) => path.join(i18nDir, f));
  const generated = "// Auto Generated by config2ts, DO NOT EDIT\n\n" + GetTsStringFromFileList(sources);
  const committed = fs.readFileSync(path.join(i18nDir, "ui.ts"), "utf-8");
  assert.equal(generated, committed, "website/src/i18n/ui.ts is stale — run npm run fixtures:regen");
});

test("site i18n table covers all three languages for every key", function () {
  const committed = fs.readFileSync(path.join(i18nDir, "ui.ts"), "utf-8");
  // Every row in ui.ts must carry non-empty zh/en/ja values; a missing
  // translation would silently render an empty label on the site.
  const rows = committed.split("key: '").slice(1);
  assert.ok(rows.length >= 20, `expected a populated table, got ${rows.length} rows`);
  for (const row of rows) {
    const key = row.slice(0, row.indexOf("'"));
    for (const field of ["zh", "en", "ja"]) {
      assert.ok(new RegExp(`${field}: '[^']+'`).test(row), `key "${key}" is missing a ${field} translation`);
    }
  }
});
