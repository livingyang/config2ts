#!/usr/bin/env node
// Regenerate fixtures/<case>/expected.ts from the source tables in each case
// directory. Golden files are committed; after regenerating, review the diff
// manually before committing — never treat a failing golden test as a signal
// to blindly rewrite expected.ts.
//
// Usage: npm run fixtures:regen   (builds lib first)

const fs = require("fs");
const path = require("path");
const { GetTsStringFromUnits, collectConvertUnits, GetTsStringFromFileList, GetValidFileList } = require("../lib/config2ts");

const rootDir = path.join(__dirname, "..");
const fixturesDir = path.join(rootDir, "fixtures");
const HEADER = "// Auto Generated by config2ts, DO NOT EDIT\n\n";

const caseDirs = fs
  .readdirSync(fixturesDir, { withFileTypes: true })
  .filter((e) => e.isDirectory())
  .map((e) => e.name)
  .sort();

if (caseDirs.length === 0) {
  console.error(`no fixture cases found under ${fixturesDir}`);
  process.exit(1);
}

let updated = 0;
for (const caseName of caseDirs) {
  const caseDir = path.join(fixturesDir, caseName);
  // collectConvertUnits resolves the case directory: plain files become one
  // unit each, and homogeneous subdirectories merge into a single virtual
  // table named after the directory (see fixtures/08-story).
  const units = collectConvertUnits(caseDir);
  if (units.length === 0) {
    console.warn(`skip ${caseName}: no csv/ini/toml source tables`);
    continue;
  }
  const generated = HEADER + GetTsStringFromUnits(units);
  const outPath = path.join(caseDir, "expected.ts");
  const prev = fs.existsSync(outPath) ? fs.readFileSync(outPath, "utf-8") : null;
  fs.writeFileSync(outPath, generated);
  if (prev === generated) {
    console.log(`=  ${caseName}/expected.ts (unchanged)`);
  } else {
    updated++;
    console.log(prev === null ? `+  ${caseName}/expected.ts (new)` : `~  ${caseName}/expected.ts (updated)`);
  }
}

console.log(`\n${caseDirs.length} cases, ${updated} changed. Review the diff before committing.`);

// A composite golden: merge tables from several cases in ONE call, mixing CSV
// (with cross-table refs) and non-CSV formats. Per-case goldens can't cover
// that — they only ever see one directory — so the "everything merged into a
// single file" path keeps its own golden under tests/golden/.
const MERGED = {
  outFile: path.join(rootDir, "tests", "golden", "merged-formats.expected.ts"),
  cases: ["03-cross-ref", "06-ini-toml"],
};
const mergedSources = MERGED.cases.flatMap(function (caseName) {
  const caseDir = path.join(fixturesDir, caseName);
  return GetValidFileList(fs.readdirSync(caseDir))
    .sort()
    .map((f) => path.join(caseDir, f));
});
const mergedGenerated = HEADER + GetTsStringFromFileList(mergedSources);
const mergedPrev = fs.existsSync(MERGED.outFile) ? fs.readFileSync(MERGED.outFile, "utf-8") : null;
fs.mkdirSync(path.dirname(MERGED.outFile), { recursive: true });
fs.writeFileSync(MERGED.outFile, mergedGenerated);
console.log(
  mergedPrev === mergedGenerated
    ? "=  tests/golden/merged-formats.expected.ts (unchanged)"
    : "~  tests/golden/merged-formats.expected.ts (updated)",
);

// The demo site dogfoods this tool: its own trilingual UI strings table
// (website/src/i18n/ui.csv) is compiled to ui.ts by config2ts as well.
const i18nDir = path.join(rootDir, "website", "src", "i18n");
const i18nSources = fs.existsSync(i18nDir) ? GetValidFileList(fs.readdirSync(i18nDir)).sort() : [];
if (i18nSources.length === 0) {
  console.log("skip website/src/i18n: no source table found");
  process.exit(0);
}
const i18nOut = path.join(i18nDir, "ui.ts");
const i18nGenerated = HEADER + GetTsStringFromFileList(i18nSources.map((f) => path.join(i18nDir, f)));
const i18nPrev = fs.existsSync(i18nOut) ? fs.readFileSync(i18nOut, "utf-8") : null;
fs.writeFileSync(i18nOut, i18nGenerated);
console.log(i18nPrev === i18nGenerated ? "=  website/src/i18n/ui.ts (unchanged)" : "~  website/src/i18n/ui.ts (updated)");
